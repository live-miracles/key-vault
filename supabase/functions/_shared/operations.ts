export type Operation<N extends OperationName> = (
    store: Store,
    ctx: Context,
    input: Operations[N]['input'],
) => Promise<Operations[N]['output']>;

export const operations: { [N in OperationName]: Operation<N> } = {
    getAllData,
    getStatus,
    getBunryuSettings,
    addEvent,
    editEvent,
    deleteEvent,
    getTrash,
    restoreEvent,
    getAdmins,
    addAdmin,
    removeAdmin,
    addRole,
    editRole,
    deleteRole,
    addInput,
    editInput,
    reorderInputs,
    deleteInput,
    addKey,
    editKey,
    deleteKey,
};

// Runs the operation with this name, or fails with "not found". The name and input come from
// the outside world, so nothing about them is trusted here.
export async function callOperation(
    store: Store,
    ctx: Context,
    name: string,
    input: unknown,
): Promise<unknown> {
    if (!Object.hasOwn(operations, name))
        throw new ApiError('not_found', `Unknown operation: ${name}.`);
    return (operations[name as OperationName] as Operation<OperationName>)(
        store,
        ctx,
        input as never,
    );
}

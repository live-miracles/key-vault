// The operations the browser calls, ported from src/Code.ts. The rules (who may do what,
// what is validated) are the same; the storage is behind `Store` so the Edge Function can
// use Postgres and the tests an in-memory copy. Only erasable TypeScript syntax is used so
// the tests can import this file with plain Node.

import {
    ACTIONS,
    ROLES,
    getEventRoles,
    hasEventAccess,
    hasKeyAccess,
    hasKeyColorAccess,
    hasInputAccess,
    hasRoleAccess,
    type EventRoles,
} from './access.ts';
import {
    buildStatusReport,
    type PipelineRow,
    type InstanceInfo,
    type StatusRow,
} from './status.ts';

export interface EventItem {
    id: string;
    name: string;
}
export interface RoleItem {
    id: string;
    event: string;
    email: string;
    type: string;
    input: string;
}
export interface InputItem {
    id: string;
    event: string;
    name: string;
    order: string;
}
export interface KeyItem {
    id: string;
    event: string;
    name: string;
    input: string;
    server: string;
    key: string;
    server2: string;
    key2: string;
    link: string;
    color: string;
    remarks: string;
    // Who last added or edited it, what they did ('added' or 'edited'), and when (ISO time).
    // Empty for a destination made before this was recorded.
    updatedBy: string;
    updatedAction: string;
    updatedAt: string;
}
export interface Data {
    events: EventItem[];
    roles: RoleItem[];
    inputs: InputItem[];
    keys: KeyItem[];
}

// Ids are generated by the database (random UUIDs), never chosen by the caller.
export interface Store {
    load(): Promise<Data>;
    loadStatus(): Promise<{
        rows: StatusRow[];
        pipelines: PipelineRow[];
        instances: InstanceInfo[];
    }>;
    createEvent(
        name: string,
        adminEmail: string | null,
    ): Promise<{ event: EventItem; adminRole: RoleItem | null }>;
    updateEvent(id: string, name: string): Promise<void>;
    deleteEvent(id: string): Promise<void>; // also removes its roles, keys and inputs
    createRole(role: Omit<RoleItem, 'id'>): Promise<RoleItem>;
    updateRole(id: string, role: Omit<RoleItem, 'id' | 'event'>): Promise<void>;
    deleteRole(id: string): Promise<void>;
    createInput(event: string, name: string): Promise<InputItem>;
    updateInput(id: string, name: string): Promise<void>;
    reorderInputs(event: string, ids: string[]): Promise<void>;
    deleteInput(id: string): Promise<void>;
    createKey(key: Omit<KeyItem, 'id'>): Promise<KeyItem>;
    updateKey(id: string, key: Omit<KeyItem, 'id' | 'event'>): Promise<void>;
    deleteKey(id: string): Promise<void>;
}

export interface Context {
    email: string;
    isAppOwner: boolean;
    hashSecret: string;
    // KEY_VAULT_SECRET itself, which bunryu is given; hashSecret is derived from it.
    secret?: string;
    ingestUrl?: string;
    nowMs: number;
}

export type Result<T = unknown> = { success: true; data: T } | { success: false; error: string };

const ok = <T>(data: T): Result<T> => ({ success: true, data });
const fail = (error: string): Result<never> => ({ success: false, error });
const invalid = (value: unknown) => fail('Invalid parameters: ' + JSON.stringify(value));
const denied = (ctx: Context) => fail('Access denied for email: ' + ctx.email);

export const KEY_COLORS = { NONE: '', ERROR: '1', WARNING: '3', CONFIGURED: '6' } as const;

const MAX_NAME = 200;
const MAX_TEXT = 2000;
const MAX_EMAIL = 254;
const EMAIL_PATTERN = /^[^\s@,;:<>()[\]"\\]+@[^\s@,;:<>()[\]"\\]+\.[^\s@,;:<>()[\]"\\]+$/;

function str(value: unknown): string {
    return String(value ?? '');
}

function tooLong(fields: [string, unknown, number][]): Result<never> | null {
    for (const [label, value, max] of fields) {
        if (str(value).length > max) return fail(`${label} must be at most ${max} characters.`);
    }
    return null;
}

export function normalizeKeyColor(color: unknown): string {
    const value = str(color).trim();
    return (Object.values(KEY_COLORS) as string[]).includes(value) ? value : KEY_COLORS.NONE;
}

// An input id is an opaque string, or "*" where a role covers every input.
export function normalizeInputId(id: unknown, allowAll = false): string {
    const inputId = str(id).trim();
    return allowAll && inputId === '*' ? '*' : inputId;
}

// An input is valid for an event only when it is one of that event's own inputs.
function isValidInput(data: Data, event: unknown, input: unknown, allowAll = false): boolean {
    const id = normalizeInputId(input, allowAll);
    return (allowAll && id === '*') || data.inputs.some((i) => i.id === id && i.event === event);
}

function hasInputName(data: Data, event: string, name: string, exceptId = ''): boolean {
    return data.inputs.some(
        (i) =>
            i.event === event &&
            i.id !== exceptId &&
            i.name.trim().toLowerCase() === name.toLowerCase(),
    );
}

function hasStreamingConfigChanged(oldKey: KeyItem, key: Partial<KeyItem>): boolean {
    return (['server', 'key', 'server2', 'key2'] as const).some(
        (field) => str(oldKey[field]) !== str(key[field]),
    );
}

export async function sha256Hex(text: string): Promise<string> {
    const digest = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(text));
    return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, '0')).join('');
}

function rolesOf(ctx: Context, data: Data): EventRoles {
    return getEventRoles(ctx.email, data.events, data.roles, ctx.isAppOwner);
}

// ===== Read =====

export async function getAllData(store: Store, ctx: Context, etag?: string) {
    const data = await store.load();
    const currentEtag = await sha256Hex(JSON.stringify(data));
    if (etag === currentEtag) return ok({ etag: currentEtag });

    const eventRoles = rolesOf(ctx, data);
    return ok({
        etag: currentEtag,
        userEmail: ctx.email,
        isAppOwner: ctx.isAppOwner,
        // Each event's inputs, limited to those whose streams this user may see.
        inputs: data.inputs.filter((i) => hasKeyAccess(eventRoles, ACTIONS.VIEW, i.event, i.id)),
        events: data.events.filter((e) => hasEventAccess(eventRoles, ACTIONS.VIEW, e.id)),
        roles: data.roles.filter((r) => hasRoleAccess(eventRoles, ACTIONS.VIEW, r.event, r.type)),
        keys: data.keys.filter((k) => hasKeyAccess(eventRoles, ACTIONS.VIEW, k.event, k.input)),
    });
}

// The status of each key the user may see, and of the inputs those keys use, from bunryu's
// last heartbeats.
export async function getStatus(store: Store, ctx: Context) {
    const data = await store.load();
    const eventRoles = rolesOf(ctx, data);
    const visible = data.keys.filter((k) =>
        hasKeyAccess(eventRoles, ACTIONS.VIEW, k.event, k.input),
    );
    const usedInputs = new Set(visible.map((k) => k.input));
    const inputs = data.inputs.filter((l) => usedInputs.has(l.id));
    const { rows, pipelines, instances } = await store.loadStatus();
    return ok(
        await buildStatusReport(
            visible,
            rows,
            instances,
            ctx.hashSecret,
            ctx.nowMs,
            pipelines,
            inputs,
        ),
    );
}

// What bunryu's `key_vault` setting needs. Owners only: it contains KEY_VAULT_SECRET.
// bunryu derives the token and the hash secret from it, as secrets.ts does here.
export async function getBunryuSettings(_store: Store, ctx: Context) {
    if (!ctx.isAppOwner) return denied(ctx);
    if (!ctx.secret || !ctx.ingestUrl) {
        return fail('KEY_VAULT_SECRET is not set on the server.');
    }
    return ok({ url: ctx.ingestUrl, secret: ctx.secret });
}

// ===== Events =====

export async function addEvent(store: Store, ctx: Context, event: any) {
    if (!event || !str(event.name).trim()) return invalid(event);
    const long = tooLong([['Name', event.name, MAX_NAME]]);
    if (long) return long;

    const data = await store.load();
    const eventRoles = rolesOf(ctx, data);
    if (!hasEventAccess(eventRoles, ACTIONS.CREATE)) return denied(ctx);

    const created = await store.createEvent(
        str(event.name).trim(),
        eventRoles['*'] ? null : ctx.email,
    );
    return ok({ ...created.event, ...(created.adminRole ? { adminRole: created.adminRole } : {}) });
}

export async function editEvent(store: Store, ctx: Context, event: any) {
    if (!event || !event.id || !str(event.name).trim()) return invalid(event);
    const long = tooLong([['Name', event.name, MAX_NAME]]);
    if (long) return long;

    const data = await store.load();
    const eventRoles = rolesOf(ctx, data);
    const old = data.events.find((e) => e.id === event.id);
    if (!old || !hasEventAccess(eventRoles, ACTIONS.VIEW, old.id)) {
        return fail('Event not found: ' + event.id);
    }
    if (!hasEventAccess(eventRoles, ACTIONS.UPDATE, event.id)) return denied(ctx);

    const name = str(event.name).trim();
    await store.updateEvent(event.id, name);
    return ok({ ...old, name });
}

export async function deleteEvent(store: Store, ctx: Context, id: unknown) {
    if (!id) return invalid(id);

    const data = await store.load();
    const eventRoles = rolesOf(ctx, data);
    const event = data.events.find((e) => e.id === id);
    if (!event || !hasEventAccess(eventRoles, ACTIONS.VIEW, event.id)) {
        return fail('Event not found: ' + id);
    }
    if (!hasEventAccess(eventRoles, ACTIONS.DELETE, event.id)) return denied(ctx);

    await store.deleteEvent(event.id);
    return ok(true);
}

// ===== Roles =====

function cleanRole(role: any) {
    const type = str(role.type);
    return {
        ...role,
        email: str(role.email).trim().toLowerCase(),
        type,
        input:
            type === ROLES.ADMIN || type === ROLES.OWNER ? '*' : normalizeInputId(role.input, true),
    };
}

function roleProblem(role: any): Result<never> | null {
    if (!(Object.values(ROLES) as string[]).includes(role.type)) return fail('Invalid role type.');
    if (role.email.length > MAX_EMAIL || !EMAIL_PATTERN.test(role.email)) {
        return fail(`"${role.email.slice(0, 80)}" is not a valid email address.`);
    }
    return null;
}

export async function addRole(store: Store, ctx: Context, payload: any) {
    if (!payload || !payload.event || !payload.email || !payload.type) return invalid(payload);
    const role = cleanRole(payload);
    const problem = roleProblem(role);
    if (problem) return problem;

    const data = await store.load();
    const eventRoles = rolesOf(ctx, data);
    if (!isValidInput(data, role.event, role.input, true)) {
        return fail('Input not found: ' + role.input);
    }
    if (!hasRoleAccess(eventRoles, ACTIONS.CREATE, role.event, role.type)) return denied(ctx);

    return ok(
        await store.createRole({
            event: role.event,
            email: role.email,
            type: role.type,
            input: role.input,
        }),
    );
}

export async function editRole(store: Store, ctx: Context, payload: any) {
    if (
        !payload ||
        !payload.id ||
        !payload.event ||
        !payload.email ||
        !payload.type ||
        !payload.input
    ) {
        return invalid(payload);
    }
    const role = cleanRole(payload);
    const problem = roleProblem(role);
    if (problem) return problem;

    const data = await store.load();
    const eventRoles = rolesOf(ctx, data);
    const old = data.roles.find((r) => r.id === role.id);
    if (!old) return fail('Role not found: ' + role.id);
    if (!isValidInput(data, old.event, role.input, true)) {
        return fail('Input not found: ' + role.input);
    }
    if (
        !hasRoleAccess(eventRoles, ACTIONS.UPDATE, role.event, role.type) ||
        !hasRoleAccess(eventRoles, ACTIONS.UPDATE, old.event, old.type)
    ) {
        return denied(ctx);
    }

    // A role stays in the event it was created in, as a sheet row did.
    await store.updateRole(old.id, {
        email: role.email,
        type: role.type,
        input: role.input,
    });
    return ok({ ...role, event: old.event });
}

export async function deleteRole(store: Store, ctx: Context, id: unknown) {
    if (!id) return invalid(id);

    const data = await store.load();
    const eventRoles = rolesOf(ctx, data);
    const role = data.roles.find((r) => r.id === id);
    if (!role) return fail('Role not found: ' + id);
    if (!hasRoleAccess(eventRoles, ACTIONS.DELETE, role.event, role.type)) return denied(ctx);

    await store.deleteRole(role.id);
    return ok(true);
}

// ===== Inputs =====
// An input belongs to one event. That event's admins (and owners) manage its list.

function inputEvent(data: Data, eventRoles: EventRoles, eventId: unknown) {
    const event = data.events.find((e) => e.id === eventId);
    return event && hasEventAccess(eventRoles, ACTIONS.VIEW, event.id) ? event : null;
}

export async function addInput(store: Store, ctx: Context, payload: any) {
    const name = str(payload?.name).trim();
    if (!payload?.event || !name) return invalid(payload);
    const long = tooLong([['Name', name, MAX_NAME]]);
    if (long) return long;

    const data = await store.load();
    const eventRoles = rolesOf(ctx, data);
    const event = inputEvent(data, eventRoles, payload.event);
    if (!event) return fail('Event not found: ' + payload.event);
    if (!hasInputAccess(eventRoles, event.id)) return denied(ctx);
    if (hasInputName(data, event.id, name))
        return fail('This event already has an input called "' + name + '".');

    return ok(await store.createInput(event.id, name));
}

export async function editInput(store: Store, ctx: Context, payload: any) {
    if (!payload || !payload.id || !str(payload.name).trim()) return invalid(payload);
    const id = normalizeInputId(payload.id);
    const name = str(payload.name).trim();
    const long = tooLong([['Name', name, MAX_NAME]]);
    if (long) return long;

    const data = await store.load();
    const eventRoles = rolesOf(ctx, data);
    const old = data.inputs.find((i) => i.id === id);
    if (!old || !inputEvent(data, eventRoles, old.event)) return fail('Input not found: ' + id);
    if (!hasInputAccess(eventRoles, old.event)) return denied(ctx);
    if (hasInputName(data, old.event, name, id))
        return fail('This event already has an input called "' + name + '".');

    await store.updateInput(id, name);
    return ok({ ...old, name });
}

// The ids of one event's inputs, in the order they should be shown.
export async function reorderInputs(store: Store, ctx: Context, payload: any) {
    if (!payload || !payload.event || !Array.isArray(payload.ids)) return invalid(payload);
    const ids = payload.ids.map((id: unknown) => normalizeInputId(id));

    const data = await store.load();
    const eventRoles = rolesOf(ctx, data);
    const event = inputEvent(data, eventRoles, payload.event);
    if (!event) return fail('Event not found: ' + payload.event);
    if (!hasInputAccess(eventRoles, event.id)) return denied(ctx);

    const own = data.inputs.filter((i) => i.event === event.id);
    const current = new Set(own.map((i) => i.id));
    const requested = new Set(ids);
    if (
        ids.length !== own.length ||
        requested.size !== ids.length ||
        ids.some((id: string) => !current.has(id))
    ) {
        return fail('Input list mismatch');
    }
    if (ids.length === 0) return ok([]);

    await store.reorderInputs(event.id, ids);
    return ok(
        ids.map((id: string, index: number) => ({
            ...own.find((i) => i.id === id)!,
            order: String(index + 1),
        })),
    );
}

export async function deleteInput(store: Store, ctx: Context, payload: unknown) {
    if (!payload) return invalid(payload);
    const id = normalizeInputId(payload);

    const data = await store.load();
    const eventRoles = rolesOf(ctx, data);
    const old = data.inputs.find((i) => i.id === id);
    if (!old || !inputEvent(data, eventRoles, old.event)) return fail('Input not found: ' + id);
    if (!hasInputAccess(eventRoles, old.event)) return denied(ctx);
    if (data.keys.some((k) => k.input === id) || data.roles.some((r) => r.input === id)) {
        return fail(
            'This input still has destinations or shared people. Remove them first, then delete the input.',
        );
    }

    await store.deleteInput(id);
    return ok(true);
}

// ===== Keys =====

const COLOR_DENIED = 'Only owners or admins can edit key colors.';

// What the browser may set: never who edited it or when, the server records that itself.
type KeyFields = Omit<KeyItem, 'id' | 'updatedBy' | 'updatedAction' | 'updatedAt'>;

// Who did what and when, from the signed-in email and the server's clock.
function lastEdit(ctx: Context, action: 'added' | 'edited') {
    return {
        updatedBy: ctx.email,
        updatedAction: action,
        updatedAt: new Date(ctx.nowMs).toISOString(),
    };
}

function cleanKey(payload: any): KeyFields & { id?: string } {
    return {
        id: payload.id,
        event: str(payload.event),
        name: str(payload.name).trim(),
        input: normalizeInputId(payload.input),
        server: str(payload.server).trim(),
        key: str(payload.key).trim(),
        server2: str(payload.server2).trim(),
        key2: str(payload.key2).trim(),
        link: str(payload.link).trim(),
        color: normalizeKeyColor(payload.color),
        remarks: str(payload.remarks).trim(),
    };
}

function keyTooLong(key: KeyFields) {
    return tooLong([
        ['Name', key.name, MAX_NAME],
        ['Server', key.server, MAX_TEXT],
        ['Key', key.key, MAX_TEXT],
        ['Backup server', key.server2, MAX_TEXT],
        ['Backup key', key.key2, MAX_TEXT],
        ['Link', key.link, MAX_TEXT],
        ['Remarks', key.remarks, MAX_TEXT],
    ]);
}

export async function addKey(store: Store, ctx: Context, payload: any) {
    if (
        !payload ||
        !payload.event ||
        !payload.name ||
        !payload.input ||
        !payload.server ||
        !payload.key
    ) {
        return invalid(payload);
    }
    const key = cleanKey(payload);
    const long = keyTooLong(key);
    if (long) return long;

    const data = await store.load();
    const eventRoles = rolesOf(ctx, data);
    if (!isValidInput(data, key.event, key.input)) return fail('Input not found: ' + key.input);
    if (!hasKeyAccess(eventRoles, ACTIONS.CREATE, key.event, key.input)) return denied(ctx);
    if (!data.events.some((e) => e.id === key.event)) return fail('Event not found: ' + key.event);
    if (key.color !== KEY_COLORS.NONE && !hasKeyColorAccess(eventRoles, key.event)) {
        return fail(COLOR_DENIED);
    }

    const { id: _ignored, ...fields } = key;
    return ok(await store.createKey({ ...fields, ...lastEdit(ctx, 'added') }));
}

export async function editKey(store: Store, ctx: Context, payload: any) {
    if (
        !payload ||
        !payload.id ||
        !payload.event ||
        !payload.name ||
        !payload.input ||
        !payload.server ||
        !payload.key
    ) {
        return invalid(payload);
    }
    const key = cleanKey(payload);
    const long = keyTooLong(key);
    if (long) return long;

    const data = await store.load();
    const eventRoles = rolesOf(ctx, data);
    const old = data.keys.find((k) => k.id === key.id);
    if (!old) return fail('Key not found: ' + key.id);
    if (key.event !== old.event) return fail('Cannot move key between events: ' + key.id);
    if (!isValidInput(data, key.event, key.input)) return fail('Input not found: ' + key.input);
    if (
        !hasKeyAccess(eventRoles, ACTIONS.UPDATE, key.event, key.input) ||
        !hasKeyAccess(eventRoles, ACTIONS.UPDATE, old.event, old.input)
    ) {
        return denied(ctx);
    }

    // A changed destination is a different stream, so a color set for the old one goes.
    if (hasStreamingConfigChanged(old, key)) {
        key.color = KEY_COLORS.NONE;
    } else if (
        key.color !== normalizeKeyColor(old.color) &&
        !hasKeyColorAccess(eventRoles, key.event)
    ) {
        return fail(COLOR_DENIED);
    }

    const { id: _id, event: _event, ...fields } = key;
    const edit = lastEdit(ctx, 'edited');
    await store.updateKey(old.id, { ...fields, ...edit });
    return ok({ ...key, ...edit, id: old.id });
}

export async function deleteKey(store: Store, ctx: Context, id: unknown) {
    if (!id) return invalid(id);

    const data = await store.load();
    const eventRoles = rolesOf(ctx, data);
    const key = data.keys.find((k) => k.id === id);
    if (!key) return fail('Key not found: ' + id);
    if (!hasKeyAccess(eventRoles, ACTIONS.DELETE, key.event, key.input)) return denied(ctx);

    await store.deleteKey(key.id);
    return ok(true);
}


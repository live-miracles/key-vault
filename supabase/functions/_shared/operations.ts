// The operations the browser calls. The rules (who may do what, what is valid) are here; the
// storage is behind `Store` so the Edge Function can use Postgres, and the tests and the demo
// an in-memory copy. Every operation returns its result or throws an ApiError. Only erasable
// TypeScript syntax is used so Node, Deno and the bundler all read this file as it is.

import { createAccess } from './access.ts';
import type { Access, Standing } from './access.ts';
import {
    destinationNameProblem,
    destinationProblem,
    findClash,
    isPlatform,
    normalizeBackup,
} from './platforms.ts';
import { buildStatusReport } from './status.ts';
import type { InstanceInfo, PipelineRow, StatusRow } from './status.ts';
import { ApiError, ROLE_TYPES, TRASH_DAYS } from './types.ts';
import type {
    AdminRow,
    AppData,
    Data,
    EventRow,
    EventView,
    InputRow,
    InputView,
    KeyFields,
    KeyRow,
    KeyView,
    OperationName,
    Operations,
    RoleRow,
    RoleType,
    RoleView,
    TrashRow,
} from './types.ts';

// Ids are generated by the database (random UUIDs), never chosen by the caller.
export interface Store {
    load(): Promise<Data>;
    loadStatus(): Promise<{
        rows: StatusRow[];
        pipelines: PipelineRow[];
        instances: InstanceInfo[];
    }>;
    createEvent(name: string): Promise<EventRow>;
    updateEvent(id: string, name: string): Promise<void>;
    // The event leaves `load()` with its roles, inputs and keys, but is kept whole.
    trashEvent(id: string, deletedBy: string, deletedAt: string): Promise<void>;
    restoreEvent(id: string): Promise<void>;
    // Every event in the trash, expired or not.
    loadTrash(): Promise<TrashRow[]>;
    // Removes for good the events deleted before this time (ISO), with their roles, keys and inputs.
    purgeTrash(before: string): Promise<void>;
    createAdmin(email: string, addedBy: string): Promise<AdminRow>;
    deleteAdmin(id: string): Promise<void>;
    createRole(role: Omit<RoleRow, 'id'>): Promise<RoleRow>;
    updateRole(id: string, role: Pick<RoleRow, 'email' | 'type' | 'input'>): Promise<void>;
    deleteRole(id: string): Promise<void>;
    createInput(event: string, name: string): Promise<InputRow>;
    updateInput(id: string, name: string): Promise<void>;
    reorderInputs(event: string, ids: string[]): Promise<void>;
    deleteInput(id: string): Promise<void>;
    createKey(key: Omit<KeyRow, 'id'>): Promise<KeyRow>;
    updateKey(id: string, key: Omit<KeyRow, 'id' | 'event'>): Promise<void>;
    deleteKey(id: string): Promise<void>;
}

export interface Context {
    email: string;
    // Named in KEY_VAULT_OWNER_EMAILS: an owner, whom nobody can remove in the app. Owners
    // can do everything an admin can, and also open bunryu's settings, which hold the secret.
    isAppOwner: boolean;
    // Everyone named in KEY_VAULT_OWNER_EMAILS, lowercase, for listing them.
    ownerEmails?: string[];
    hashSecret: string;
    // KEY_VAULT_SECRET itself, which bunryu is given; hashSecret is derived from it.
    secret?: string;
    ingestUrl?: string;
    nowMs: number;
}

const TRASH_MS = TRASH_DAYS * 24 * 60 * 60 * 1000;

const MAX_NAME = 200;
const MAX_TEXT = 2000;
const MAX_EMAIL = 254;
const EMAIL_PATTERN = /^[^\s@,;:<>()[\]"\\]+@[^\s@,;:<>()[\]"\\]+\.[^\s@,;:<>()[\]"\\]+$/;

// ===== Reading a request =====

const invalid = (message: string) => new ApiError('invalid', message);
const denied = () => new ApiError('denied', 'You do not have permission to do that.');
const notFound = (what: string) => new ApiError('not_found', `${what} was not found.`);

function body(value: unknown): Record<string, unknown> {
    if (!value || typeof value !== 'object' || Array.isArray(value)) {
        throw invalid('The request is not valid.');
    }
    return value as Record<string, unknown>;
}

function text(value: unknown): string {
    return String(value ?? '').trim();
}

// A text field the request must have.
function required(payload: Record<string, unknown>, field: string): string {
    const value = text(payload[field]);
    if (!value) throw invalid(`The request is missing "${field}".`);
    return value;
}

function limit(label: string, value: string, max: number) {
    if (value.length > max) throw invalid(`${label} must be at most ${max} characters.`);
}

async function load(store: Store, ctx: Context) {
    const data = await store.load();
    const standing: Standing = ctx.isAppOwner
        ? 'owner'
        : data.admins.some((a) => a.email === ctx.email)
          ? 'admin'
          : null;
    return { data, access: createAccess(ctx.email, standing, data.roles) };
}

// ===== What the browser is sent =====

function eventView(access: Access, event: EventRow): EventView {
    return { ...event, can: access.describeEvent(event.id) };
}
function roleView(access: Access, role: RoleRow): RoleView {
    return { ...role, canChange: access.canChangeRole(role.event) };
}
function inputView(access: Access, input: InputRow): InputView {
    return { ...input, canAddKeys: access.canChangeKey(input.event, input.id) };
}
function keyView(access: Access, key: KeyRow): KeyView {
    return { ...key, canChange: access.canChangeKey(key.event, key.input) };
}

// ===== Read =====

// The owners named on the server, lowercase and sorted.
function ownerEmails(ctx: Context) {
    return [...new Set((ctx.ownerEmails ?? []).map((e) => e.toLowerCase()))].sort();
}

// Everyone with access to every event: the owners, then the admins.
function everyEventPeople(data: Data, ctx: Context) {
    const owners = ownerEmails(ctx);
    return [
        ...owners.map((email) => ({ email, owner: true })),
        ...data.admins
            .filter((a) => !owners.includes(a.email))
            .map((a) => ({ email: a.email, owner: false })),
    ];
}

export async function getAllData(store: Store, ctx: Context): Promise<AppData> {
    // Housekeeping: an event that has been in the trash too long goes for good, stream keys
    // included. Nothing reads it from then on anyway, so a failure here is only logged.
    try {
        await store.purgeTrash(new Date(ctx.nowMs - TRASH_MS).toISOString());
    } catch (error) {
        console.error('Could not empty the trash:', error);
    }

    const { data, access } = await load(store, ctx);
    return {
        userEmail: ctx.email,
        isAppOwner: ctx.isAppOwner,
        canCreateEvents: access.canCreateEvent(),
        canRestoreEvents: access.canRestoreEvents(),
        canManageAdmins: access.canManageAdmins(),
        everyEvent: data.events.some((e) => access.canViewRoles(e.id))
            ? everyEventPeople(data, ctx)
            : [],
        events: data.events
            .filter((e) => access.canViewEvent(e.id))
            .map((e) => eventView(access, e)),
        roles: data.roles
            .filter((r) => access.canViewRoles(r.event))
            .map((r) => roleView(access, r)),
        inputs: data.inputs
            .filter((i) => access.canViewKey(i.event, i.id))
            .map((i) => inputView(access, i)),
        keys: data.keys
            .filter((k) => access.canViewKey(k.event, k.input))
            .map((k) => keyView(access, k)),
    };
}

// The status of each destination the user may see, and of the inputs those destinations use,
// from bunryu's last heartbeats.
export async function getStatus(
    store: Store,
    ctx: Context,
): Promise<Operations['getStatus']['output']> {
    const { data, access } = await load(store, ctx);
    const visible = data.keys.filter((k) => access.canViewKey(k.event, k.input));
    const usedInputs = new Set(visible.map((k) => k.input));
    const inputs = data.inputs.filter((i) => usedInputs.has(i.id));
    const { rows, pipelines, instances } = await store.loadStatus();
    return buildStatusReport(
        visible,
        rows,
        instances,
        ctx.hashSecret,
        ctx.nowMs,
        pipelines,
        inputs,
    );
}

// What bunryu's `key_vault` setting needs. Owners only, not admins: it contains KEY_VAULT_SECRET.
// bunryu derives the token and the hash secret from it, as secrets.ts does here.
export async function getBunryuSettings(_store: Store, ctx: Context) {
    if (!ctx.isAppOwner) throw denied();
    if (!ctx.secret || !ctx.ingestUrl) {
        throw new ApiError('unavailable', 'KEY_VAULT_SECRET is not set on the server.');
    }
    return { url: ctx.ingestUrl, secret: ctx.secret };
}

// ===== Events =====

export async function addEvent(store: Store, ctx: Context, input: Operations['addEvent']['input']) {
    const payload = body(input);
    const name = required(payload, 'name');
    limit('Name', name, MAX_NAME);

    const { access } = await load(store, ctx);
    if (!access.canCreateEvent()) throw denied();

    // Admins have access to every event, so nobody needs a role in the one they create.
    return eventView(access, await store.createEvent(name));
}

export async function editEvent(
    store: Store,
    ctx: Context,
    input: Operations['editEvent']['input'],
) {
    const payload = body(input);
    const id = required(payload, 'id');
    const name = required(payload, 'name');
    limit('Name', name, MAX_NAME);

    const { data, access } = await load(store, ctx);
    const old = data.events.find((e) => e.id === id);
    if (!old || !access.canViewEvent(id)) throw notFound('The event');
    if (!access.canChangeEvent(id)) throw denied();

    await store.updateEvent(id, name);
    return { id, name };
}

export async function deleteEvent(
    store: Store,
    ctx: Context,
    input: Operations['deleteEvent']['input'],
) {
    const id = required(body(input), 'id');

    const { data, access } = await load(store, ctx);
    if (!data.events.some((e) => e.id === id) || !access.canViewEvent(id))
        throw notFound('The event');
    if (!access.canChangeEvent(id)) throw denied();

    // Not deleted yet: it waits in the trash for an admin to restore it.
    await store.trashEvent(id, ctx.email, new Date(ctx.nowMs).toISOString());
}

// The events in the trash that can still be restored, the latest deleted first. Admins only.
async function restorable(store: Store, ctx: Context) {
    const { access } = await load(store, ctx);
    if (!access.canRestoreEvents()) throw denied();
    const cutoff = ctx.nowMs - TRASH_MS;
    return (await store.loadTrash())
        .filter((t) => Date.parse(t.deletedAt) > cutoff)
        .sort((a, b) => Date.parse(b.deletedAt) - Date.parse(a.deletedAt));
}

export async function getTrash(store: Store, ctx: Context) {
    return (await restorable(store, ctx)).map((t) => ({
        ...t,
        expiresAt: new Date(Date.parse(t.deletedAt) + TRASH_MS).toISOString(),
    }));
}

export async function restoreEvent(
    store: Store,
    ctx: Context,
    input: Operations['restoreEvent']['input'],
) {
    const id = required(body(input), 'id');

    const trashed = (await restorable(store, ctx)).find((t) => t.id === id);
    if (!trashed) throw notFound('The deleted event');

    await store.restoreEvent(id);
    return { id, name: trashed.name };
}

// ===== Admins =====
// An admin has access to every event and manages the other admins. The owners are named on the
// server (KEY_VAULT_OWNER_EMAILS): they are listed here but have no row, so nothing in the app
// can remove them.

async function adminsOnly(store: Store, ctx: Context) {
    const loaded = await load(store, ctx);
    if (!loaded.access.canManageAdmins()) throw denied();
    return { ...loaded, owners: ownerEmails(ctx) };
}

export async function getAdmins(store: Store, ctx: Context) {
    const { data, owners } = await adminsOnly(store, ctx);
    // Someone named on the server is shown there only, even if they were added here before.
    const admins = data.admins.filter((a) => !owners.includes(a.email));
    return { owners, admins };
}

export async function addAdmin(store: Store, ctx: Context, input: Operations['addAdmin']['input']) {
    const email = cleanEmail(body(input).email);
    const { data, owners } = await adminsOnly(store, ctx);
    if (owners.includes(email)) throw new ApiError('conflict', `${email} is already an owner.`);
    if (data.admins.some((a) => a.email === email)) {
        throw new ApiError('conflict', `${email} is already an admin.`);
    }
    return store.createAdmin(email, ctx.email);
}

export async function removeAdmin(
    store: Store,
    ctx: Context,
    input: Operations['removeAdmin']['input'],
) {
    const id = required(body(input), 'id');
    const { data, owners } = await adminsOnly(store, ctx);
    const admin = data.admins.find((a) => a.id === id);
    if (!admin) throw notFound('The admin');
    if (owners.includes(admin.email)) {
        throw new ApiError('denied', 'This owner is set on the server and cannot be removed here.');
    }
    if (admin.email === ctx.email) {
        throw invalid('You cannot remove yourself. Ask another admin to do it.');
    }
    await store.deleteAdmin(id);
}

// ===== Roles =====

function cleanEmail(value: unknown): string {
    const email = text(value).toLowerCase();
    if (email.length > MAX_EMAIL || !EMAIL_PATTERN.test(email)) {
        throw invalid(`"${email.slice(0, 80)}" is not a valid email address.`);
    }
    return email;
}

function cleanRole(payload: Record<string, unknown>) {
    const type = text(payload.type) as RoleType;
    if (!ROLE_TYPES.includes(type)) {
        throw invalid('Choose a role: viewer or editor. Admins are added under Admins.');
    }
    const email = cleanEmail(payload.email);
    // A role names one input, or null for every input of the event.
    let input: string | null = null;
    if (payload.input !== null && payload.input !== undefined) {
        input = text(payload.input) || null;
    }
    return { email, type, input };
}

function requireInput(data: Data, event: string, input: string | null) {
    if (input !== null && !data.inputs.some((i) => i.id === input && i.event === event)) {
        throw notFound('The input');
    }
}

export async function addRole(store: Store, ctx: Context, input: Operations['addRole']['input']) {
    const payload = body(input);
    const event = required(payload, 'event');
    const role = cleanRole(payload);

    const { data, access } = await load(store, ctx);
    if (!data.events.some((e) => e.id === event)) throw notFound('The event');
    requireInput(data, event, role.input);
    if (!access.canAddRole(event)) throw denied();

    return roleView(access, await store.createRole({ event, ...role }));
}

export async function editRole(store: Store, ctx: Context, input: Operations['editRole']['input']) {
    const payload = body(input);
    const id = required(payload, 'id');
    const role = cleanRole(payload);

    const { data, access } = await load(store, ctx);
    const old = data.roles.find((r) => r.id === id);
    if (!old) throw notFound('The role');
    requireInput(data, old.event, role.input);
    if (!access.canChangeRole(old.event)) throw denied();

    // A role stays in the event it was created in.
    await store.updateRole(id, role);
    return roleView(access, { id, event: old.event, ...role });
}

export async function deleteRole(
    store: Store,
    ctx: Context,
    input: Operations['deleteRole']['input'],
) {
    const id = required(body(input), 'id');

    const { data, access } = await load(store, ctx);
    const role = data.roles.find((r) => r.id === id);
    if (!role) throw notFound('The role');
    if (!access.canChangeRole(role.event)) throw denied();

    await store.deleteRole(id);
}

// ===== Inputs =====
// An input belongs to one event. Admins manage its list.

function manageableEvent(data: Data, access: Access, event: string) {
    if (!data.events.some((e) => e.id === event) || !access.canViewEvent(event)) {
        throw notFound('The event');
    }
    if (!access.canManageInputs(event)) throw denied();
}

function checkInputName(data: Data, event: string, name: string, exceptId = '') {
    const clash = data.inputs.some(
        (i) =>
            i.event === event &&
            i.id !== exceptId &&
            i.name.trim().toLowerCase() === name.toLowerCase(),
    );
    if (clash) throw new ApiError('conflict', `This event already has an input called "${name}".`);
}

export async function addInput(store: Store, ctx: Context, input: Operations['addInput']['input']) {
    const payload = body(input);
    const event = required(payload, 'event');
    const name = required(payload, 'name');
    limit('Name', name, MAX_NAME);

    const { data, access } = await load(store, ctx);
    manageableEvent(data, access, event);
    checkInputName(data, event, name);

    return inputView(access, await store.createInput(event, name));
}

export async function editInput(
    store: Store,
    ctx: Context,
    input: Operations['editInput']['input'],
) {
    const payload = body(input);
    const id = required(payload, 'id');
    const name = required(payload, 'name');
    limit('Name', name, MAX_NAME);

    const { data, access } = await load(store, ctx);
    const old = data.inputs.find((i) => i.id === id);
    if (!old || !access.canViewEvent(old.event)) throw notFound('The input');
    manageableEvent(data, access, old.event);
    checkInputName(data, old.event, name, id);

    await store.updateInput(id, name);
    return { id, name };
}

// The ids of one event's inputs, in the order they should be shown.
export async function reorderInputs(
    store: Store,
    ctx: Context,
    input: Operations['reorderInputs']['input'],
) {
    const payload = body(input);
    const event = required(payload, 'event');
    if (!Array.isArray(payload.ids)) throw invalid('The request is missing "ids".');
    const ids = payload.ids.map(text);

    const { data, access } = await load(store, ctx);
    manageableEvent(data, access, event);

    const own = new Set(data.inputs.filter((i) => i.event === event).map((i) => i.id));
    if (
        ids.length !== own.size ||
        new Set(ids).size !== ids.length ||
        ids.some((id) => !own.has(id))
    ) {
        throw new ApiError(
            'conflict',
            'The list of inputs changed. Reload the page and try again.',
        );
    }
    if (ids.length > 0) await store.reorderInputs(event, ids);
}

export async function deleteInput(
    store: Store,
    ctx: Context,
    input: Operations['deleteInput']['input'],
) {
    const id = required(body(input), 'id');

    const { data, access } = await load(store, ctx);
    const old = data.inputs.find((i) => i.id === id);
    if (!old || !access.canViewEvent(old.event)) throw notFound('The input');
    manageableEvent(data, access, old.event);
    if (data.keys.some((k) => k.input === id) || data.roles.some((r) => r.input === id)) {
        throw new ApiError(
            'conflict',
            'This input still has destinations or shared people. Remove them first, then delete the input.',
        );
    }

    await store.deleteInput(id);
}

// ===== Destinations (keys) =====

// Who did what and when, from the signed-in email and the server's clock.
function lastEdit(ctx: Context, action: 'added' | 'edited') {
    return {
        updatedBy: ctx.email,
        updatedAction: action,
        updatedAt: new Date(ctx.nowMs).toISOString(),
    };
}

// What the browser sent, cleaned and with the platform's backup rules applied.
function cleanKey(payload: Record<string, unknown>): KeyFields {
    const key = normalizeBackup({
        event: required(payload, 'event'),
        name: required(payload, 'name'),
        input: required(payload, 'input'),
        platform: required(payload, 'platform'),
        streamKey: required(payload, 'streamKey'),
        backupPlatform: text(payload.backupPlatform),
        backupStreamKey: text(payload.backupStreamKey),
        link: text(payload.link),
        remarks: text(payload.remarks),
    });
    limit('Name', key.name, MAX_NAME);
    for (const [label, value] of [
        ['Stream key', key.streamKey],
        ['Backup stream key', key.backupStreamKey],
        ['Watch link', key.link],
        ['Notes', key.remarks],
    ]) {
        limit(label, value, MAX_TEXT);
    }
    return key;
}

// What makes a destination invalid or a duplicate; throws.
function checkKey(data: Data, key: KeyFields, exceptId = '') {
    const nameProblem = destinationNameProblem(key.name);
    if (nameProblem) throw invalid(nameProblem);
    if (!isPlatform(key.platform)) throw invalid("Please choose where you're streaming to.");
    const problem = destinationProblem(key);
    if (problem) throw invalid(problem.message);

    const others = data.keys.filter((k) => k.event === key.event && k.id !== exceptId);
    const clash = findClash(key, others);
    if (clash) throw new ApiError('conflict', clash.message);
}

export async function addKey(store: Store, ctx: Context, input: Operations['addKey']['input']) {
    const key = cleanKey(body(input));

    const { data, access } = await load(store, ctx);
    if (!data.events.some((e) => e.id === key.event)) throw notFound('The event');
    requireInput(data, key.event, key.input);
    if (!access.canChangeKey(key.event, key.input)) throw denied();
    checkKey(data, key);

    return keyView(access, await store.createKey({ ...key, ...lastEdit(ctx, 'added') }));
}

export async function editKey(store: Store, ctx: Context, input: Operations['editKey']['input']) {
    const payload = body(input);
    const id = required(payload, 'id');
    const key = cleanKey(payload);

    const { data, access } = await load(store, ctx);
    const old = data.keys.find((k) => k.id === id);
    if (!old) throw notFound('The destination');
    if (key.event !== old.event) throw invalid('A destination cannot move to another event.');
    requireInput(data, key.event, key.input);
    if (!access.canChangeKey(old.event, old.input) || !access.canChangeKey(key.event, key.input)) {
        throw denied();
    }
    checkKey(data, key, id);

    const { event: _event, ...fields } = key;
    const edit = lastEdit(ctx, 'edited');
    await store.updateKey(id, { ...fields, ...edit });
    return keyView(access, { ...key, ...edit, id });
}

export async function deleteKey(
    store: Store,
    ctx: Context,
    input: Operations['deleteKey']['input'],
) {
    const id = required(body(input), 'id');

    const { data, access } = await load(store, ctx);
    const key = data.keys.find((k) => k.id === id);
    if (!key) throw notFound('The destination');
    if (!access.canChangeKey(key.event, key.input)) throw denied();

    await store.deleteKey(id);
}

